    for asset, hx, hz, hyaw in houses:
        w, d, _ = b.size(asset)
        b.reserve(hx, hz, hyaw, w * 0.5 + 0.3, d * 0.5 + 0.3)
        b.place(asset, hx, hz, hyaw, TOWN + "/Buildings", "Town_House")

