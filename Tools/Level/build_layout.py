def build_height_field():
    field = HeightField(regional_base, MASSES, [], micro_relief)
    paths = {}
    for name, width, blend, material, control, note in PATH_SPECS:
        pts = resample(chaikin(control, 3), 0.75)
        paths[name] = {"name": name, "width": width, "edgeBlend": blend,
                       "material": material, "points": pts, "note": note}
    # The cave interior is a separate surface inside the massif; it must not carve the hill.
    for name, p in paths.items():
        if name == "Path_CaveInterior":
            continue
        field.add_conform(p["points"], p["width"] * 0.5, p["edgeBlend"] + 0.7)
    stream = resample(chaikin(STREAM_CONTROL, 3), 0.75)
    bed = [(x, y - STREAM_BED_DROP, z) for x, y, z in stream]
    # Not skippable: the channel has to stay cut under the bridge, or the water has
    # nowhere to run and vanishes into the bank at the crossing.
    # The stream is cut but not rendered. It never earned its cost: it carved a channel
    # the route had to bridge, split the lake trace, needed its own bank barrier run and
    # a widening rule, and forced a conform-priority fight with the roads -- for a
    # watercourse the player crosses once. Its channel stays because the terrain, the
    # bridge and the lake shoreline are all shaped against it; only the surface goes.
    field.add_conform(bed, STREAM_HALF_WIDTH, 2.6, skippable=False)
    return field, paths, stream


def shore_band(lake_poly, keep, inner, outer):
    """A strip of land following the shoreline, `inner` to `outer` metres inland.

    The lakeside fields were hand-drawn polygons and the lake is traced from the
    terrain, so the two drifted apart: once the shoreline was traced honestly, 99% of
    Field_Lake_ShoreGrass was underwater and it placed one clump. Deriving the band
    from the same polygon the water is built from means it cannot drift again.
    """
    cx, cz = poly_centroid(lake_poly)
    arc = [p for p in lake_poly if keep(p[0], p[1])]
    if len(arc) < 3:
        return []

    def push(p, d):
        vx, vz = p[0] - cx, p[1] - cz
        n = math.hypot(vx, vz) or 1.0
        return (round(p[0] + vx / n * d, 2), round(p[1] + vz / n * d, 2))

    near = [push(p, inner) for p in arc]
    far = [push(p, outer) for p in reversed(arc)]
    return near + far


def add_bridge_bed(field, bounds, yaw):
    """A flat bed under the bridge, so both abutments meet ground.

    Cut to the bridge's own rotated footprint rather than a circle: a radial pad
    would reach out into the banks either side of the crossing and widen the channel
    the bridge has to span, which is the problem, not the fix.
    """
    size = bounds.get("Env_Bridge_Wood", {}).get("size")
    if not size:
        return
    r = math.radians(yaw)
    c, sn = abs(math.cos(r)), abs(math.sin(r))
    # Shrunk, and with a very short blend. The bed has to drop 1.33 m below the road
    # for the abutments to meet ground, and anything that drop reaches on the road
    # itself is a step the player cannot climb: at a 1.5 m blend it put 0.64 m and
    # 0.60 m steps on Path_RouteSpine either side of the crossing, against a 0.45 m
    # limit. Confined to the deck's own footprint, the drop happens under the deck,
    # which is what the player walks across instead.
    half_x = (size[0] * c + size[2] * sn) * 0.5 - 0.25
    half_z = (size[0] * sn + size[2] * c) * 0.5 - 0.25
    field.add_pad(BRIDGE_X, BRIDGE_Z, half_x, half_z, BRIDGE_BED, 0.35)


def add_cave_outcrop(field):
    """A small shelf in front of the cave mouth, so there is something to stand on.

    Pushed *forward* of the mouth and kept short, which the first version was not: a
    5.5 m pad with a 5.5 m blend levelled about eleven metres of ground around the
    mouth and flattened away the very cliff the site was chosen for. The arch then
    stood as a free hoop in the middle of the gorge with sky behind it. The rock
    immediately behind the opening is the whole point, so the pad must not reach it.

    Flat rather than a mass because the player stands on it to enter; a mass would
    dome it.
    """
    r = math.radians(CAVE_MOUTH_YAW)
    fx, fz = math.sin(r), math.cos(r)          # out of the hill
    cx = CAVE_MOUTH_X + fx * CAVE_SHELF_OFFSET
    cz = CAVE_MOUTH_Z + fz * CAVE_SHELF_OFFSET
    height = field.height(CAVE_MOUTH_X, CAVE_MOUTH_Z)
    field.add_pad(cx, cz, CAVE_SHELF_HALF_X, CAVE_SHELF_HALF_Z, height, 2.2)


def add_building_pads(field, bounds):
    """Cut a level platform under every building.

    Evaluated against the field as it stands *before* any pad is added, so a pad takes
    the natural ground height at the building's own centre rather than inheriting a
    neighbour's platform. The blend is short: a house sits on a terrace with a visible
    edge, not in the middle of a saucer.
    """
    for asset, hx, hz, hyaw in BUILDINGS:
        size = bounds.get(asset, {}).get("size")
        if not size:
            continue
        height = field.height(hx, hz)
        rad = math.radians(hyaw)
        c, sn = abs(math.cos(rad)), abs(math.sin(rad))
        # Rotated footprint's axis-aligned half extents, plus a doorstep margin.
        half_x = (size[0] * c + size[2] * sn) * 0.5 + 0.6
        half_z = (size[0] * sn + size[2] * c) * 0.5 + 0.6
        field.add_pad(hx, hz, half_x, half_z, height, 2.4)


def apply_skips(field):
    """Suspend the *road* conform under bridged spans, so water passes beneath rather
    than the road dragging the ground up with it.

    This used to fall back to `field.raw`, which drops every conform -- including the
    stream channel. The bed then sat above the water surface at the one point where
    the two must meet, so the stream disappeared into the ground under the bridge and
    the bridge read as standing on dry dirt between two unconnected pools. Falling
    back to the non-skippable conforms instead keeps the channel cut.
    """
    original = field.height

    def height(x, z):
        for (cx, cz), r, _ in CONFORM_SKIPS:
            d = math.hypot(x - cx, z - cz)
            if d < r:
                w = smootherstep(d / r)
                # `original`, not `field.height` -- the latter is this very closure by
                # the time it runs, and calling it would recurse forever.
                return lerp(original(x, z, skippable=False), original(x, z), w)
        return original(x, z)

    field.height = height
    return field


