class Builder:
    """Accumulates placements. Rejects anything that overlaps something solid, sits in a
    road corridor, or lands on ground too steep to stand on."""

    def __init__(self, bounds, baked, paths, rng):
        self.bounds = bounds
        self.baked = baked
        self.paths = paths
        self.rng = rng
        self.objects = []
        self.occupancy = []      # (x, z, radius)
        self.footprints = []     # (x, z, yaw, half_w, half_d) no-build rectangles
        self.counters = {}
        self.rejected = 0
        self.reasons = {}
        self.surface_override = None   # while placing inside the cave

    # -- queries ------------------------------------------------------------
    def size(self, name):
        s = self.bounds[name]["size"]
        return s[0], s[1], s[2]

    def subfamily(self, name):
        return self.bounds[name]["subfamily"]

    def solid_radius(self, name, scale):
        w, d, _ = self.size(name)
        return 0.5 * max(w, d) * scale * SOLID_FRACTION.get(self.subfamily(name), 0.45) * 2.0

    def ground(self, x, z):
        if self.surface_override is not None:
            return self.surface_override
        return self.baked.at(x, z)

    def road_clearance(self, x, z):
        """Metres from the nearest road edge; negative means inside the corridor."""
        best = 1e9
        for p in self.paths.values():
            d, _, _ = closest_on_polyline(x, z, p["points"])
            best = min(best, d - p["width"] * 0.5)
        return best

    def blocked(self, x, z, radius, margin):
        for ox, oz, orad in self.occupancy:
            if (x - ox) ** 2 + (z - oz) ** 2 < (radius + orad + margin) ** 2:
                return True
        for fx, fz, fyaw, hw, hd in self.footprints:
            a = math.radians(-fyaw)
            dx, dz = x - fx, z - fz
            lx = dx * math.cos(a) - dz * math.sin(a)
            lz = dx * math.sin(a) + dz * math.cos(a)
            if abs(lx) < hw + radius and abs(lz) < hd + radius:
                return True
        return False

    # -- placement ----------------------------------------------------------
    def place(self, asset, x, z, yaw, parent, tag_prefix, scale=1.0, y=None,
              road_margin=0.35, jitter_yaw=0.0, tag="Untagged", record=True,
              lift=0.0):
        if jitter_yaw:
            yaw += self.rng.uniform(-jitter_yaw, jitter_yaw)
        info = self.bounds[asset]
        n = self.counters.get(tag_prefix, 0) + 1
        self.counters[tag_prefix] = n
        yy = (self.ground(x, z) if y is None else y) + lift
        obj = {
            "prefab": info["path"],
            "name": "%s_%02d" % (tag_prefix, n),
            "parent": parent,
            "position": [round(x, 3), round(yy, 3), round(z, 3)],
            "rotation": [0.0, round(yaw % 360.0, 2), 0.0],
            "scale": [round(scale, 3)] * 3,
            "layer": LAYER_BY_FAMILY.get(info["family"], "Environment"),
            "tag": tag,
            "static": True,
        }
        self.objects.append(obj)
        if record:
            self.occupancy.append((x, z, self.solid_radius(asset, scale)))
        _ = road_margin
        return obj

    def try_place(self, asset, x, z, yaw, parent, tag_prefix, scale=1.0,
                  road_margin=0.5, margin=0.05, max_slope=32.0, jitter_yaw=0.0,
                  allow_on_road=False, tag="Untagged"):
        r = self.solid_radius(asset, scale)
        if not allow_on_road and self.road_clearance(x, z) < road_margin + r * 0.5:
            return self._reject("road", tag_prefix)
        if self.blocked(x, z, r, margin):
            return self._reject("overlap", tag_prefix)
        if self.surface_override is None and self.baked.slope_degrees(x, z) > max_slope:
            return self._reject("slope", tag_prefix)
        return self.place(asset, x, z, yaw, parent, tag_prefix, scale=scale,
                          jitter_yaw=jitter_yaw, tag=tag)

    def _reject(self, why, tag_prefix):
        self.rejected += 1
        key = "%s/%s" % (tag_prefix, why)
        self.reasons[key] = self.reasons.get(key, 0) + 1
        return None

    def prop_run(self, asset, points, parent, tag_prefix, gaps=(), offset=0.0,
                 flip=False, sink=0.06):
        """Lay a modular barrier end to end along a polyline.

        Env_Ledge_* and Env_Riverbank_* are built for exactly this and were placed
        nowhere: their pivot is the module corner, they run along +X, and they are
        1.19 m and 0.60 m tall. That height is the whole point. The terrain is a smooth
        height field on a 1 m grid with no vertical discontinuity anywhere, so
        PlayerLocomotion's 0.45 m step limit never fires and the only gate terrain can
        offer is a face steeper than its 48 degree slope limit -- which needs adjacent
        samples to differ by more than 1.11 m. Every ledge and every riverbank in this
        layout was authored as a barrier and measured as walkable. A prop with a
        vertical collider face is absolute at any grid resolution.

        `gaps` are (x, z, radius) circles the run skips: a barrier with no way through
        is a wall, and the design wants crossings -- the bridge, the stepping stones,
        the plunge pool.
        """
        info = self.bounds[asset]
        length = info["size"][0]
        placed = 0
        run = 0.0
        total = polyline_length(points)
        while run + length <= total + 0.01:
            mid = run + length * 0.5
            t = mid / total if total > 0 else 0.0
            ax, az = offset_point(points, t, 0, 0.0)
            if any(math.hypot(ax - gx, az - gz) < gr for gx, gz, gr in gaps):
                run += length
                continue

            # Tangent at the module's midpoint, so a curved bank does not stair-step.
            _, _, tangent = closest_on_polyline(ax, az, points)
            yaw = yaw_towards(tangent[0], tangent[1]) - 90.0
            if flip:
                yaw += 180.0
            r = math.radians(yaw)
            nx, nz = math.cos(r), -math.sin(r)      # the module's own +X
            px, pz = ax - nx * length * 0.5, az - nz * length * 0.5
            if offset:
                px += -nz * offset
                pz += nx * offset

            self.place(asset, px, pz, yaw, parent, tag_prefix,
                       y=self.ground(px, pz) - sink, road_margin=0.0)
            placed += 1
            run += length
        return placed

    def reserve(self, x, z, yaw, half_w, half_d):
        self.footprints.append((x, z, yaw, half_w, half_d))

    # -- composed placement idioms -----------------------------------------
    def tree_wall(self, control, side, offsets, count, palette, parent, tag,
                  scale=(0.9, 1.25), jitter=1.6):
        """A hedgerow: trees strung along a polyline at two or three depths, deliberately
        close enough to overlap. Every reference shot shows corridor edges as a continuous
        mass, never as evenly spaced individuals."""
        pts = resample(chaikin(control, 2), 1.0)
        made = 0
        for i in range(count):
            t = (i + 0.5) / count
            off = offsets[i % len(offsets)] + self.rng.uniform(-jitter, jitter)
            x, z = offset_point(pts, t, side, off)
            x += self.rng.uniform(-1.1, 1.1)
            z += self.rng.uniform(-1.1, 1.1)
            a = self.rng.choice(palette)
            if self.try_place(a, x, z, self.rng.uniform(0, 360), parent, tag,
                              scale=self.rng.uniform(*scale), road_margin=1.0,
                              margin=-0.55, max_slope=48.0):
                made += 1
        return made

    def clump(self, cx, cz, radius, count, palette, parent, tag,
              scale=(0.9, 1.2), road_margin=0.8, max_slope=42.0, margin=0.0):
        """A cluster. Reference rocks and trees arrive in groups of three to seven with a
        size gradient, not as a uniform sprinkle."""
        made = 0
        for _ in range(count):
            a = self.rng.random() * math.tau
            r = radius * math.sqrt(self.rng.random())
            x, z = cx + math.cos(a) * r, cz + math.sin(a) * r
            asset = self.rng.choice(palette)
            s = lerp(scale[1], scale[0], r / max(radius, 1e-6)) * self.rng.uniform(0.9, 1.1)
            if self.try_place(asset, x, z, self.rng.uniform(0, 360), parent, tag,
                              scale=s, road_margin=road_margin, margin=margin,
                              max_slope=max_slope):
                made += 1
        return made

    def fence_run(self, control, prefab, parent, tag, gaps=()):
        """Butted modules along a polyline -- one continuous run, correct yaw, no jitter.
        A fence with random rotation reads as debris."""
        w = self.size(prefab)[0]
        pts = resample(chaikin(control, 2), 0.5)
        total = polyline_length(pts)
        n = max(1, int(total / w))
        made = 0
        for i in range(n):
            t = (i + 0.5) / n
            x, z = offset_point(pts, t, 1, 0.0)
            skip = False
            for gx, gz, gr in gaps:
                if math.hypot(x - gx, z - gz) < gr:
                    skip = True
            if skip:
                continue
            _, _, tangent = closest_on_polyline(x, z, pts)
            yaw = yaw_towards(tangent[0], tangent[1]) + 90.0
            if self.try_place(prefab, x, z, yaw, parent, tag, road_margin=0.15,
                              margin=-0.35, max_slope=40.0):
                made += 1
        return made

    def street_furniture(self, control, prefab, parent, tag, spacing, offsets, yaw_face=None):
        """Lamps and benches down a street. Alternating sides at a fixed interval is what
        makes a street read as designed rather than decorated."""
        pts = resample(chaikin(control, 2), 0.5)
        total = polyline_length(pts)
        n = max(1, int(total / spacing))
        made = 0
        for i in range(n):
            t = (i + 0.5) / n
            side, off = offsets[i % len(offsets)]
            x, z = offset_point(pts, t, side, off)
            _, _, tangent = closest_on_polyline(x, z, pts)
            yaw = yaw_face if yaw_face is not None else \
                yaw_towards(-side * tangent[1], side * tangent[0])
            if self.try_place(prefab, x, z, yaw, parent, tag, road_margin=0.2, margin=0.0):
                made += 1
        return made


