    print("wrote %s" % OUT_PATH)
    print("  objects            %d" % len(b.objects))
    print("  foliage fields     %d  (%d instances for the builder to scatter)"
          % (len(FOLIAGE_FIELDS), sum(f["instanceBudget"] for f in FOLIAGE_FIELDS)))
    print("  paths              %d  (%.0f m of road)"
          % (len(path_json), sum(p["lengthMetres"] for p in path_json)))
    print("  height grid        %d x %d at %.1f m" % (baked.nx, baked.nz, GRID_STEP))
    print("  rejected           %d" % b.rejected)
    if os.environ.get("LAYOUT_VERBOSE"):
        for k, v in sorted(b.reasons.items(), key=lambda kv: -kv[1])[:24]:
            print("      %-34s %d" % (k, v))
    return doc


