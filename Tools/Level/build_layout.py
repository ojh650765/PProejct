    bowl = next(m for m in MASSES if m.name == "Mass_LakeBowl")

    def _in_bowl(ix, iz):
        x, z = X0 + ix * GRID_STEP, Z0 + iz * GRID_STEP
        return z >= 26.0 and poly_sdf(x, z, bowl.polygon) < bowl.shoulder * 0.72

