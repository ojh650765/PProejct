"""Generate Assets/Game/Data/Levels/slice_layout.json -- the vertical slice's placement data.

    python Tools/Level/build_layout.py

Design intent lives in this file. The JSON is an artefact; tune the numbers here and re-run.
Geometry helpers live in Tools/Level/worldgen.py.

-----------------------------------------------------------------------------------------
WHAT THIS IS A REWRITE OF, AND WHY
-----------------------------------------------------------------------------------------
The first layout was built in engine and rejected. Five specific failures, and the fix for
each, drawn from Nintendo Switch Pokemon maps (BDSP Routes 201/205, SwSh Wedgehurst,
Legends: Arceus Obsidian Fieldlands -- see Tools/Level/reference/):

1. 226 separate 2 m paving tiles at varied rotations, overlapping and z-fighting.
   -> Roads are now `paths`: a centreline, a width and an edge blend. ONE mesh per road,
      generated by the builder. This file places zero path tiles.

2. Eight flat decks at fixed heights.
   -> Terrain is one continuous composed height field: a regional base, landform masses
      with shoulders, a valley dish, a lake bowl, stream channels, and road conform.
      Every Y in the file is sampled from the baked grid that is also emitted, so the
      props and the ground cannot disagree.

3. Buildings scattered at arbitrary angles on open ground.
   -> Aster Town is composed the way Wedgehurst is: one paved main street from the south
      bridge to the north gate, widening into a plaza at the fork; every house on a fenced
      plot with its front addressing the street; the lab staged on a raised forecourt at
      the head of the plaza, facing the player's spawn down the camera's own axis.

4. Ramps and ledges specified with no geometry under them.
   -> `terrain.ramps`, `terrain.ledges`, `terrain.cliffs`, `terrain.caves` are first-class
      entries with the geometry a builder needs, and the height field already carves the
      ramp corridors, so the two agree by construction.

5. 4,682 objects, 2,201 of them grass clumps, reading as noise.
   -> Ground cover is no longer placement data. `foliageFields` declares a polygon, a
      density and a weighted prefab set, and the builder instances it. `objects` holds
      only things whose position is a composition decision. The middle of every space is
      deliberately empty, which is what the reference screenshots actually show.
-----------------------------------------------------------------------------------------
"""

