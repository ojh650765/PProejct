          [(5.5, 6.0), (10, 8.0), (13, 10.5), (13.5, 12.5), (9, 10.0), (5.0, 7.0)],
          8.5, [("Env_TallGrass_Cluster_C", 4), ("Env_TallGrass_Cluster_A", 3),
                 ("Env_TallGrass_Cluster_D", 3)],
