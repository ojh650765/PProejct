def regional_base(x, z):
    """A very gentle whole-map tilt: the land falls from the town shoulder in the south-west
    toward the lake basin in the north-east. Deliberately shallow (0.8 m across 114 m) so the
    lake bowl is the only landform that reaches below the waterline -- an earlier version
    tilted hard enough to flood the entire east of the map."""
    return 0.35 - 0.0060 * (x - X0) - 0.0040 * (z - Z0)


def micro_relief(x, z):
    """Low-amplitude undulation everywhere, so no part of the map is a plate.
    Amplitude is under 0.4 m total -- readable in silhouette, invisible to locomotion."""
    return (0.17 * math.sin(0.117 * x) + 0.13 * math.cos(0.101 * z)
            + 0.09 * math.sin(0.283 * x + 0.241 * z)
            + 0.05 * math.cos(0.451 * z - 0.377 * x))


