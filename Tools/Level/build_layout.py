FOLIAGE_FIELDS = []


def field(name, kind, polygon, density, prefabs, parent, zone, note,
          scale=(0.85, 1.2), encounters=False):
    poly = [(round(p[0], 2), round(p[1], 2)) for p in polygon]
    area = poly_area(poly)
    FOLIAGE_FIELDS.append({
        "name": name,
        "kind": kind,
        "zone": zone,
        "parent": parent,
        "polygon": [list(p) for p in poly],
        "areaSquareMetres": round(area, 1),
        "densityPerSquareMetre": density,
        "instanceBudget": int(area * density),
        "prefabs": [{"prefab": "%s/%s.fbx" % (_folder(p), p), "weight": w}
                    for p, w in prefabs],
        "scaleRange": list(scale),
        "yawJitterDegrees": 360.0,
        "rendering": "instanced",
        "conformsToHeightField": True,
        "generatesEncounters": encounters,
        "note": note,
    })
    return FOLIAGE_FIELDS[-1]


def _folder(asset):
    fam = {"Env_Grass": "Foliage", "Env_Flower": "Foliage", "Env_Fern": "Foliage",
           "Env_Bush": "Foliage", "Env_Reed": "Foliage", "Env_Lilypad": "Foliage",
           "Env_Moss": "Foliage"}
    for k, v in fam.items():
        if asset.startswith(k):
            return "%s/%s" % (ENV, v)
    return "%s/Foliage" % ENV


