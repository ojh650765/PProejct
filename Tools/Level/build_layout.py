def main():
    b, baked, paths, stream, lake_poly, stream_poly, plaza, cave_floor = build()

    # tall-grass triggers derived from the encounter fields, so the two cannot drift
    grass_triggers = []
    for f in FOLIAGE_FIELDS:
        if not f["generatesEncounters"]:
            continue
        mnx, mxx, mnz, mxz = poly_bounds([(p[0], p[1]) for p in f["polygon"]])
        cx, cz = (mnx + mxx) / 2, (mnz + mxz) / 2
        grass_triggers.append({
            "name": f["name"].replace("Field_", "Grass_"),
            "field": f["name"],
            "centre": [round(cx, 2), round(baked.at(cx, cz) + 0.1, 2), round(cz, 2)],
            "triggerSize": [round(mxx - mnx, 2), 2.0, round(mxz - mnz, 2)],
            "polygon": f["polygon"],
            "clumpCount": f["instanceBudget"],
            "generatesEncounters": True, "setsTraversalState": True,
            "layer": "ZoneTrigger", "component": "TallGrassPatch",
        })

    gameplay = gameplay_block(baked)
    gameplay["tallGrassPatches"] = grass_triggers

    path_json = []
    for name, width, blend, material, control, note in PATH_SPECS:
        p = paths[name]
        pts = p["points"]
        path_json.append({
            "name": name, "width": width, "edgeBlend": blend, "material": material,
            "centreline": [[round(x, 2), round(y, 3), round(z, 2)] for x, y, z in pts],
            "lengthMetres": round(polyline_length(pts), 1),
            "controlPoints": [[round(c[0], 2), round(c[1], 2), round(c[2], 2)]
                              for c in control],
            "conformsTerrain": name != "Path_CaveInterior",
            "note": note,
        })

    counts = {}
    for o in b.objects:
        key = os.path.splitext(os.path.basename(o["prefab"]))[0]
        sub = b.bounds[key]["subfamily"]
        counts[sub] = counts.get(sub, 0) + 1
    by_parent = {}
    for o in b.objects:
        by_parent[o["parent"]] = by_parent.get(o["parent"], 0) + 1

    doc = {
        "schema": "pokelab.level.layout/2",
        "generatedBy": "Tools/Level/build_layout.py",
        "seed": SEED,
        "units": ("1 unit = 1 metre, Y up, models face +Z, pivots at the base. Roads and "
                  "terrain are generated meshes described by this file, not placed props."),
        "reference": {
            "note": "Redesigned against Nintendo Switch Pokemon maps after the first "
                    "attempt was rejected. Screens studied are listed in "
                    "Tools/Level/reference/SOURCES.md.",
            "principles": [
                "A road is one continuous ribbon with a worn edge, never a field of tiles.",
                "The walkable band is 3-5x the road width, and the space either side of "
                "the road is mostly empty grass -- density lives at the corridor edges.",
                "Corridor edges are massed: overlapping tree clusters and cliff feet, "
                "never evenly spaced individuals.",
                "Terrain gates progress -- a river with one bridge, a one-way ledge, a "
                "gorge that pinches -- rather than invisible walls.",
                "Tall grass is a contiguous field with a hard silhouette, adjacent to the "
                "road, and it is avoidable.",
                "A town has one street with a hierarchy off it; every building addresses "
                "the street from a bounded plot; the landmark is staged at the head.",
            ],
        },
        "extents": {"minX": X0, "maxX": X1, "minZ": Z0, "maxZ": Z1,
                    "note": "%.0f x %.0f m. Smaller than the rejected layout on purpose."
                            % (X1 - X0, Z1 - Z0)},
        "layerContract": LAYER_CONTRACT,
        "camera": CAMERA,
        "terrain": terrain_block(baked, paths, stream, lake_poly, stream_poly, plaza,
                                 cave_floor),
        "paths": path_json,
        "foliageFields": FOLIAGE_FIELDS,
        "zones": zones_block(),
        "gameplay": gameplay,
        "ambientAnchors": ambient_block(baked, paths, stream),
        "requiredAssets": REQUIRED_ASSETS,
        "counts": {
            "objects": len(b.objects),
            "foliageFields": len(FOLIAGE_FIELDS),
            "foliageInstanceBudget": sum(f["instanceBudget"] for f in FOLIAGE_FIELDS),
            "paths": len(path_json),
            "pathMetres": round(sum(p["lengthMetres"] for p in path_json), 1),
            "cliffs": len(doc_cliffs(baked)),
            "bySubfamily": dict(sorted(counts.items(), key=lambda kv: -kv[1])),
            "byParent": dict(sorted(by_parent.items())),
            "rejectedPlacements": b.rejected,
        },
        "objects": b.objects,
    }

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=1)
    print("wrote %s" % OUT_PATH)
    print("  objects            %d" % len(b.objects))
    print("  foliage fields     %d  (%d instances for the builder to scatter)"
          % (len(FOLIAGE_FIELDS), sum(f["instanceBudget"] for f in FOLIAGE_FIELDS)))
    print("  paths              %d  (%.0f m of road)"
          % (len(path_json), sum(p["lengthMetres"] for p in path_json)))
    print("  height grid        %d x %d at %.1f m" % (baked.nx, baked.nz, GRID_STEP))
    print("  rejected           %d" % b.rejected)
    if os.environ.get("LAYOUT_VERBOSE"):
        for k, v in sorted(b.reasons.items(), key=lambda kv: -kv[1])[:24]:
            print("      %-34s %d" % (k, v))
    return doc


