"""Cast table and canvas policy.

The two id spaces in this project do not agree and one of the collisions is
live: national dex 25 is Pikachu, while game species id 25 is Rattata.  Every
lookup here goes through GAME_ID -> dex, never the other way round by
coincidence, and the mapping below is cross-checked against the original
artwork filenames (which encode the dex number: Pikachu was 002501.png).

The collision is not the exception, it is the rule.  Across the 53 species in
this cast only two -- Bulbasaur and Ivysaur -- have game id equal to dex, while
48 have a game id that is some *other* species' dex: game 16 is Butterfree
while dex 16 is Pidgey, and both are in this table at once.  Reading the wrong
column does not raise an error anywhere, it just hands over the wrong animal.
So the mapping is transcribed from the game's own registry
(Assets/StreamingAssets/pokelab/species.json), which stores `Id` and
`NationalDex` on the same record, rather than derived.  check_ids.py re-checks
every row against that registry and against the staged filenames.
"""

